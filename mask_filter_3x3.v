// Streaming 3x3 majority filter for a 320x240 1-bit foreground mask.
// Input sample_en must pulse once for each SOURCE pixel in raster order.
// The window ending at (x,y) produces the filtered result for center
// pixel (x-1,y-1).  A 4-of-9 vote is used: it removes isolated speckles
// while preserving/filling more of the foreground than a strict 5-of-9 vote.
module mask_filter_3x3 (
    input  wire        clk,
    input  wire        clear,
    input  wire        sample_en,
    input  wire [8:0]  src_x,
    input  wire [7:0]  src_y,
    input  wire        raw_mask,
    output reg         out_we,
    output reg  [16:0] out_addr,
    output reg         out_mask,
    output reg         mask_ready
);
    reg line1 [0:319];   // previous source row
    reg line2 [0:319];   // row before previous

    reg c1 = 1'b0, c2 = 1'b0;
    reg p1 = 1'b0, p2 = 1'b0;
    reg q1 = 1'b0, q2 = 1'b0;

    wire prev1 = line1[src_x];
    wire prev2 = line2[src_x];

    // 3x3 window:
    // q2 q1 prev2
    // p2 p1 prev1
    // c2 c1 raw_mask
    wire [3:0] ones =
        {3'b000,q2} + {3'b000,q1} + {3'b000,prev2} +
        {3'b000,p2} + {3'b000,p1} + {3'b000,prev1} +
        {3'b000,c2} + {3'b000,c1} + {3'b000,raw_mask};

    wire [8:0] center_x = src_x - 9'd1;
    wire [7:0] center_y = src_y - 8'd1;
    wire [16:0] center_addr =
        {1'b0, center_y, 8'b0} +
        {3'b000, center_y, 6'b0} +
        {8'b00000000, center_x};

    always @(posedge clk) begin
        out_we <= 1'b0;

        if (clear) begin
            c1 <= 1'b0; c2 <= 1'b0;
            p1 <= 1'b0; p2 <= 1'b0;
            q1 <= 1'b0; q2 <= 1'b0;
            out_addr <= 17'd0;
            out_mask <= 1'b0;
            mask_ready <= 1'b0;
        end else if (sample_en) begin
            // Once x>=2 and y>=2, a complete 3x3 neighborhood exists.
            if ((src_x >= 9'd2) && (src_y >= 8'd2)) begin
                out_we   <= 1'b1;
                out_addr <= center_addr;
                out_mask <= (ones >= 4'd4);
            end

            // Shift the two previous columns for each of the three rows.
            if (src_x == 9'd0) begin
                c2 <= 1'b0; c1 <= raw_mask;
                p2 <= 1'b0; p1 <= prev1;
                q2 <= 1'b0; q1 <= prev2;
            end else begin
                c2 <= c1;       c1 <= raw_mask;
                p2 <= p1;       p1 <= prev1;
                q2 <= q1;       q1 <= prev2;
            end

            // Rotate line memories: current -> line1, old line1 -> line2.
            line2[src_x] <= prev1;
            line1[src_x] <= raw_mask;

            // The interior mask for this frame has been generated by the
            // time the last source pixel arrives.  Borders are gated off
            // in the top module.
            if ((src_x == 9'd319) && (src_y == 8'd239))
                mask_ready <= 1'b1;
        end
    end
endmodule
